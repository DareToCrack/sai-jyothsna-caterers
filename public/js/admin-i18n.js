const SUPPORTED_LANGUAGES = ['en', 'te'];
const LANG_STORAGE_KEY = 'sjc_lang'; // shared with the customer site

let currentLang = 'en';
try {
  if (typeof localStorage !== 'undefined') {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (SUPPORTED_LANGUAGES.includes(stored)) currentLang = stored;
  }
} catch (e) { /* private mode / Node: stay on English */ }

/**
 * Translate a key, with {name} interpolation from `params`.
 * Falls back to English when the current language lacks the key, and to
 * the key itself when no dictionary has it (so a missing key is visible
 * in the UI instead of silently blank).
 */
function t(key, params) {
  const dict = ADMIN_I18N[currentLang] || {};
  let value = dict[key];
  if (typeof value !== 'string') value = ADMIN_I18N.en[key];
  if (typeof value !== 'string') return key;
  if (params) {
    value = value.replace(/\{(\w+)\}/g, (m, name) =>
      (params[name] === undefined || params[name] === null) ? m : String(params[name]));
  }
  return value;
}

function getAdminLanguage() {
  return currentLang;
}

/**
 * Apply the current language to every tagged element in the document:
 * [data-i18n] -> textContent, [data-i18n-placeholder] -> placeholder,
 * [data-i18n-aria-label] -> aria-label, [data-i18n-title] -> title.
 * Also syncs the language <select> controls and <html lang>.
 * Safe to call in Node (no document): it just returns.
 */
function applyAdminLanguage() {
  if (typeof document === 'undefined') return;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.querySelectorAll('.lang-select').forEach((sel) => {
    sel.value = currentLang;
  });
  if (document.documentElement) document.documentElement.lang = currentLang;
}

/**
 * Switch language: persist the choice (shared with the customer site),
 * set <html lang>, apply translations, then notify the portal
 * (admin.js defines window.onAdminLanguageChange) so dynamic content —
 * the current section's tables, badges and labels — re-renders.
 */
function setAdminLanguage(lang) {
  if (!SUPPORTED_LANGUAGES.includes(lang)) lang = 'en';
  currentLang = lang;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) { /* private mode: keep it for this page only */ }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang;
  }
  applyAdminLanguage();
  if (typeof window !== 'undefined' && typeof window.onAdminLanguageChange === 'function') {
    window.onAdminLanguageChange(lang);
  }
}

const AdminI18nApi = {
  ADMIN_I18N,
  SUPPORTED_LANGUAGES,
  t,
  getAdminLanguage,
  setAdminLanguage,
  applyAdminLanguage
};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = AdminI18nApi;
}
if (typeof window !== 'undefined') {
  window.ADMIN_I18N = ADMIN_I18N;
  window.t = t;
  window.getAdminLanguage = getAdminLanguage;
  window.setAdminLanguage = setAdminLanguage;
  window.applyAdminLanguage = applyAdminLanguage;
}
