// Global Translation Helper (browser only; the Node seed uses TRANSLATIONS directly)
function translateKey(key, lang) {
  if (key && typeof key === 'object') {
    return key[lang] || key['en'] || '';
  }
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  return (dict && dict[key]) || TRANSLATIONS['en'][key] || key;
}

if (typeof window !== 'undefined') {
  window.t = function(key, lang = null) {
    if (!lang) {
      try { lang = localStorage.getItem('sjc_lang') || 'en'; } catch (e) { lang = 'en'; }
    }
    return translateKey(key, lang);
  };
  window.TRANSLATIONS = TRANSLATIONS;
  console.log('Sai Jyothsna Translations Dictionary Initialized');
}

